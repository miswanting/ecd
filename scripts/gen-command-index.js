#!/usr/bin/env node
/**
 * 从 docs/translation/Command.md 生成命令索引数据，供 <CommandIndex /> 使用。
 *
 * 产物：src/data/commandIndex.js（已提交，便于不跑脚本也能构建）。
 * 由 scripts/prelude.js 在每次 docs:build / docs:dev 前重新生成，保证与文档同步。
 */
const fs = require('fs')
const path = require('path')

const ROOT = path.resolve(__dirname, '..')
const SRC = path.join(ROOT, 'docs/translation/Command.md')
const OUT = path.join(ROOT, 'src/data/commandIndex.js')

// 与 VuePress（@mdit-vue/shared）一致的标题 slug 规则
const rControl = /[\u0000-\u001f]/g
const rSpecial = /[\s~`!@#$%^&*()\-_+=[\]{}|\\;:"'“”‘’<>,.?/]+/g
const rCombining = /[\u0300-\u036f]/g
const slugify = (str) =>
  str
    .normalize('NFKD')
    .replace(rCombining, '')
    .replace(rControl, '')
    .replace(rSpecial, '-')
    .replace(/-{2,}/g, '-')
    .replace(/^-+|-+$/g, '')
    .replace(/^(\d)/, '_$1')
    .toLowerCase()

const md = fs.readFileSync(SRC, 'utf8')

const entries = []
const groups = []
let group = ''
for (const line of md.split('\n')) {
  const h2 = /^##\s+(.*)$/.exec(line)
  if (h2) {
    group = h2[1].trim()
    groups.push(group)
    continue
  }
  const h3 = /^###\s+(.*)$/.exec(line)
  if (!h3) continue

  const raw = h3[1].trim()
  const plain = raw.replace(/`/g, '') // 渲染后的纯文本（反引号是行内代码标记）
  const nameMatch = /^([A-Za-z_][A-Za-z0-9_]*)/.exec(plain)
  const name = nameMatch ? nameMatch[1] : ''
  // 非命令的“分组标题”，如 “PRINT系列指令辅助选择器”
  const isSection = !name || /辅助选择器$/.test(plain)
  entries.push({
    name: isSection ? plain : name,
    signature: plain,
    group,
    slug: slugify(plain),
    section: isSection,
  })
}

const header = `// AUTO-GENERATED by scripts/gen-command-index.js — 请勿手动编辑。
// 数据来源：docs/translation/Command.md
`
const body =
  header +
  `\nexport const commandIndex = ${JSON.stringify(entries, null, 2)}\n` +
  `\nexport const commandGroups = ${JSON.stringify(groups, null, 2)}\n`

fs.mkdirSync(path.dirname(OUT), { recursive: true })
fs.writeFileSync(OUT, body)
console.log(
  `[gen-command-index] ${entries.length} 条命令 / ${groups.length} 个分组 -> ${path.relative(ROOT, OUT)}`,
)
