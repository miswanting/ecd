#!/usr/bin/env node
/**
 * 从只读参考工程 .ref/Emuera 提取引擎的错误 / 警告文案，生成可搜索的索引数据。
 *
 * 产物：src/data/errorMessages.js（已提交，便于不跑脚本也能构建）。
 * 若 .ref/Emuera 不存在（例如未包含参考工程的克隆），则保留现有产物不动。
 */
const fs = require('fs')
const path = require('path')

const ROOT = path.resolve(__dirname, '..')
const REF = path.join(ROOT, '.ref/Emuera/Emuera')
const OUT = path.join(ROOT, 'src/data/errorMessages.js')

if (!fs.existsSync(REF)) {
  console.log('[gen-error-index] .ref/Emuera 不存在，跳过（保留现有数据）')
  process.exit(0)
}

// level: 1 = 警告，2 = 错误，3 = 无法恢复的致命错误（对应“表示する最低警告レベル”）
const API_LEVEL = [
  ['ParserMediator.Warn', 1],
  ['new CodeEE', 2],
  ['PrintError', 2],
  ['new ExeEE', 3],
]
const PATTERN = new RegExp(
  `(${API_LEVEL.map(([a]) => a.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('|')})\\(\\s*"((?:[^"\\\\]|\\\\.)*)"`,
  'gs',
)
const LEVEL_OF = Object.fromEntries(API_LEVEL)

function walk(dir) {
  const out = []
  for (const name of fs.readdirSync(dir)) {
    const p = path.join(dir, name)
    const st = fs.statSync(p)
    if (st.isDirectory()) {
      if (name === 'obj' || name === 'bin') continue
      out.push(...walk(p))
    } else if (name.endsWith('.cs')) {
      out.push(p)
    }
  }
  return out
}

const seen = new Set()
const list = []
for (const file of walk(REF)) {
  const text = fs.readFileSync(file, 'utf8')
  for (const m of text.matchAll(PATTERN)) {
    const level = LEVEL_OF[m[1]]
    const message = m[2].replace(/\\"/g, '"').replace(/\\n/g, ' ').replace(/[(（]\s*$/, '').trim()
    // 过滤纯符号等明显不是文案的碎片
    if (message.length < 2) continue
    if (/^[\\s\"'`,.:;()[\]{}<>/|~!@#$%^&*_+=-]+$/.test(message)) continue
    const key = message.replace(/[:：]\s*$/, '')
    if (seen.has(key)) continue
    seen.add(key)
    list.push({
      message,
      level,
      file: path.relative(REF, file).replace(/\\/g, '/'),
    })
  }
}

list.sort((a, b) => a.level - b.level || a.message.localeCompare(b.message, 'ja'))

const header = `// AUTO-GENERATED by scripts/gen-error-index.js — 请勿手动编辑。
// 数据来源：.ref/Emuera（只读参考工程）的 ParserMediator.Warn / CodeEE / ExeEE / PrintError。
// level: 1 = 警告，2 = 错误，3 = 无法恢复的致命错误。
`
fs.writeFileSync(OUT, header + `\nexport const errorMessages = ${JSON.stringify(list, null, 2)}\n`)
console.log(`[gen-error-index] ${list.length} 条错误 / 警告 -> ${path.relative(ROOT, OUT)}`)
